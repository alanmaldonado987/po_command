create function public.hoy() returns date
language sql stable as $$ select (now() at time zone 'America/Bogota')::date $$;

create table public.config (
  clave text primary key,
  valor text not null default ''
);

create table public.producto (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text not null default '',
  estado text not null default 'Activo' check (estado in ('Activo', 'Pausado', 'Cerrado')),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table public.cliente (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text not null default '',
  estado text not null default 'Activo' check (estado in ('Activo', 'Pausado', 'Cerrado'))
);

create table public.actividad (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text not null default ''
);

create table public.modulo (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  producto_id bigint references public.producto (id) on delete set null,
  descripcion text not null default ''
);

create table public.persona (
  id bigint generated by default as identity primary key,
  nombre text not null,
  correo text not null default '',
  tipo text not null check (tipo in ('equipo', 'stakeholder')),
  rol text not null default '',
  frecuencia_reporte text not null default '',
  recibe text[] not null default '{}',
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table public.persona_cliente (
  persona_id bigint not null references public.persona (id) on delete cascade,
  cliente_id bigint not null references public.cliente (id) on delete cascade,
  primary key (persona_id, cliente_id)
);

create sequence public.item_codigo_seq;

create table public.item (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  producto_id bigint references public.producto (id) on delete set null,
  cliente_id bigint references public.cliente (id) on delete set null,
  actividad_id bigint references public.actividad (id) on delete set null,
  modulo_id bigint references public.modulo (id) on delete set null,
  funcionalidad text not null,
  descripcion text not null default '',
  fase text not null default '',
  alcance text not null default '',
  responsable_id bigint references public.persona (id) on delete set null,
  plan_ini date,
  plan_fin date,
  plan_pruebas_ini date,
  plan_pruebas_fin date,
  real_ini date,
  real_fin date,
  real_pruebas_ini date,
  real_pruebas_fin date,
  estado text not null default 'No iniciado'
    check (estado in ('No iniciado', 'En curso', 'Terminado, en etapa de pruebas', 'Terminado', 'Suspendido')),
  bloqueado boolean not null default false,
  motivo_bloqueo text not null default '',
  terminado_en date,
  clave_importacion text,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  eliminado_en timestamptz
);
create index item_clave_importacion_idx on public.item (clave_importacion);
create index item_cliente_idx on public.item (cliente_id) where eliminado_en is null;
create index item_responsable_idx on public.item (responsable_id) where eliminado_en is null;

create table public.nota (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.item (id) on delete cascade,
  fecha date not null default public.hoy(),
  tipo text not null default 'Seguimiento'
    check (tipo in ('Seguimiento', 'Planificación', 'Ejecución', 'Reprogramación', 'Bloqueo')),
  texto text not null,
  autor text not null default '',
  creado_en timestamptz not null default now()
);
create index nota_item_idx on public.nota (item_id);

create table public.bloqueante (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.item (id) on delete cascade,
  motivo text not null,
  severidad text not null default 'Media' check (severidad in ('Alta', 'Media', 'Baja')),
  abierto_en timestamptz not null default now(),
  escalado_en timestamptz,
  resuelto_en timestamptz
);
create index bloqueante_item_idx on public.bloqueante (item_id);
create unique index bloqueante_abierto_ux on public.bloqueante (item_id) where resuelto_en is null;

create table public.ceremonia (
  id bigint generated by default as identity primary key,
  cliente_id bigint references public.cliente (id) on delete set null,
  tipo text not null,
  titulo text not null,
  fecha_hora timestamptz not null,
  duracion_min integer not null default 60 check (duracion_min > 0),
  lugar text not null default 'Teams',
  audiencia text not null default 'equipo' check (audiencia in ('equipo', 'stakeholders', 'todos')),
  invitacion_enviada boolean not null default false,
  notas text not null default ''
);

create table public.acuerdo (
  id bigint generated by default as identity primary key,
  ceremonia_id bigint references public.ceremonia (id) on delete set null,
  origen text not null default '',
  descripcion text not null,
  responsable_id bigint references public.persona (id) on delete set null,
  fecha_limite date,
  estado text not null default 'Pendiente' check (estado in ('Pendiente', 'En curso', 'Cumplido'))
);

create table public.regla_alerta (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  descripcion text not null default '',
  categoria text not null,
  destinatarios text[] not null default '{}',
  parametro numeric not null default 0,
  hora_envio text not null default '08:00' check (hora_envio ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  activa boolean not null default true
);

create table public.alerta_programada (
  id bigint generated by default as identity primary key,
  regla_codigo text not null,
  entidad text not null,
  entidad_id bigint,
  clave_unica text,
  asunto text not null,
  cuerpo_html text not null,
  destinatarios text[] not null,
  enviar_en timestamptz not null default now(),
  estado text not null default 'Pendiente' check (estado in ('Pendiente', 'Enviada', 'Fallida', 'Cancelada')),
  intentos integer not null default 0,
  error text,
  creado_en timestamptz not null default now(),
  enviado_en timestamptz
);
create unique index alerta_clave_unica_ux on public.alerta_programada (clave_unica) where clave_unica is not null;
create index alerta_estado_idx on public.alerta_programada (estado, enviar_en);
create index alerta_entidad_idx on public.alerta_programada (entidad, entidad_id);

create table public.notificacion_log (
  id bigint generated by default as identity primary key,
  alerta_id bigint references public.alerta_programada (id) on delete set null,
  regla_codigo text,
  asunto text,
  destinatarios text,
  canal text not null default 'Correo',
  estado text not null,
  detalle text,
  fecha timestamptz not null default now()
);
create index notificacion_log_fecha_idx on public.notificacion_log (fecha desc);

create table public.auditoria (
  id bigint generated by default as identity primary key,
  entidad text not null,
  entidad_id bigint,
  accion text not null,
  detalle text not null default '',
  fecha timestamptz not null default now()
);
create index auditoria_fecha_idx on public.auditoria (fecha desc);

create table public.smtp_config (
  id boolean primary key default true check (id),
  host text not null default 'smtp.office365.com',
  puerto integer not null default 587,
  seguridad text not null default 'starttls' check (seguridad in ('starttls', 'ssl', 'none')),
  usuario text not null default '',
  password text not null default '',
  remitente text not null default '',
  nombre_remitente text not null default 'PO Command Center',
  dry_run boolean not null default true
);

