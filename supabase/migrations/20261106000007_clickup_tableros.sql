create view public.v_item with (security_invoker = true) as
with base as (
  select i.*,
         coalesce(i.plan_pruebas_fin, i.plan_fin) as fecha_compromiso,
         coalesce(i.real_pruebas_fin, i.real_fin) as fecha_entrega
  from public.item i
  where i.eliminado_en is null
),
calculado as (
  select b.*,
         case
           when b.fecha_compromiso is null then 0
           when b.estado = 'Terminado' then greatest(coalesce(b.fecha_entrega, b.fecha_compromiso) - b.fecha_compromiso, 0)
           when b.estado = 'Suspendido' then 0
           else greatest(public.hoy() - b.fecha_compromiso, 0)
         end as atraso_dias
  from base b
)
select c.*,
       case
         when lower(c.funcionalidad) = 'completo' then coalesce(m.nombre, '') || ' · completo'
         else c.funcionalidad
       end as titulo,
       c.estado not in ('Terminado', 'Suspendido') and c.atraso_dias > 0 as atrasado,
       pr.nombre as producto,
       cl.nombre as cliente,
       ac.nombre as actividad,
       m.nombre as modulo,
       pe.nombre as responsable,
       pe.correo as responsable_correo,
       pe.tablero_id as tablero_id,
       tb.nombre as tablero
from calculado c
left join public.producto pr on pr.id = c.producto_id
left join public.cliente cl on cl.id = c.cliente_id
left join public.actividad ac on ac.id = c.actividad_id
left join public.modulo m on m.id = c.modulo_id
left join public.persona pe on pe.id = c.responsable_id
left join public.clickup_tablero tb on tb.id = pe.tablero_id;

create view public.v_bloqueante_abierto with (security_invoker = true) as
select b.id, b.item_id, b.motivo, b.severidad, b.abierto_en, b.escalado_en,
       i.codigo, i.titulo, i.cliente_id, i.cliente, i.actividad, i.modulo, i.responsable, i.fecha_compromiso
from public.bloqueante b
join public.v_item i on i.id = b.item_id
where b.resuelto_en is null;

create view public.v_persona with (security_invoker = true) as
select p.*,
       coalesce(array_agg(pc.cliente_id) filter (where pc.cliente_id is not null), '{}') as cliente_ids,
       coalesce(string_agg(cl.nombre, ', ' order by cl.nombre), '') as clientes,
       (select tb.nombre from public.clickup_tablero tb where tb.id = p.tablero_id) as tablero
from public.persona p
left join public.persona_cliente pc on pc.persona_id = p.id
left join public.cliente cl on cl.id = pc.cliente_id
group by p.id;

create or replace function public.tocar_actualizado() returns trigger
language plpgsql as $$
begin
  if (to_jsonb(new) - 'actualizado_en' - 'clickup_task_id' - 'clickup_url' - 'clickup_sync_en' - 'clickup_lista_id')
     = (to_jsonb(old) - 'actualizado_en' - 'clickup_task_id' - 'clickup_url' - 'clickup_sync_en' - 'clickup_lista_id') then
    return new;
  end if;
  new.actualizado_en := now();
  return new;
end
$$;

create or replace function public.auditar() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_fila jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  v_accion text := case tg_op when 'INSERT' then 'crear' when 'DELETE' then 'eliminar' else 'editar' end;
begin
  if tg_op = 'UPDATE'
     and (to_jsonb(new) - 'actualizado_en' - 'clickup_task_id' - 'clickup_url' - 'clickup_sync_en' - 'clickup_lista_id')
       = (to_jsonb(old) - 'actualizado_en' - 'clickup_task_id' - 'clickup_url' - 'clickup_sync_en' - 'clickup_lista_id') then
    return null;
  end if;
  if tg_op = 'UPDATE' and (to_jsonb(old) ->> 'eliminado_en') is null and (v_fila ->> 'eliminado_en') is not null then
    v_accion := 'eliminar';
  end if;
  insert into public.auditoria (entidad, entidad_id, accion, detalle)
  values (
    tg_table_name,
    (v_fila ->> 'id')::bigint,
    v_accion,
    concat_ws(' ', v_fila ->> 'codigo', v_fila ->> 'nombre', v_fila ->> 'funcionalidad', v_fila ->> 'titulo')
  );
  return null;
end
$$;

create or replace function public.guardar_persona(p_data jsonb, p_clientes bigint[] default '{}', p_id bigint default null) returns bigint
language plpgsql as $$
declare
  v_id bigint := p_id;
  v_recibe text[] := array(select jsonb_array_elements_text(coalesce(p_data -> 'recibe', '[]'::jsonb)));
  v_tablero bigint := nullif(p_data ->> 'tablero_id', '')::bigint;
begin
  if public._limpiar(p_data ->> 'nombre') = '' then
    raise exception 'El nombre es obligatorio';
  end if;
  if v_id is null then
    insert into public.persona (nombre, correo, tipo, rol, frecuencia_reporte, recibe, activo, tablero_id)
    values (public._limpiar(p_data ->> 'nombre'), btrim(coalesce(p_data ->> 'correo', '')), p_data ->> 'tipo',
            coalesce(p_data ->> 'rol', ''), coalesce(p_data ->> 'frecuencia_reporte', ''), v_recibe,
            coalesce((p_data ->> 'activo')::boolean, true), v_tablero)
    returning id into v_id;
  else
    update public.persona set
      nombre = public._limpiar(p_data ->> 'nombre'), correo = btrim(coalesce(p_data ->> 'correo', '')),
      tipo = p_data ->> 'tipo', rol = coalesce(p_data ->> 'rol', ''),
      frecuencia_reporte = coalesce(p_data ->> 'frecuencia_reporte', ''), recibe = v_recibe,
      activo = coalesce((p_data ->> 'activo')::boolean, true),
      tablero_id = case when p_data ? 'tablero_id' then v_tablero else tablero_id end
    where id = v_id;
  end if;
  delete from public.persona_cliente where persona_id = v_id;
  insert into public.persona_cliente (persona_id, cliente_id)
  select v_id, unnest(p_clientes);
  return v_id;
end
$$;

create function public.destino_clickup(p_tablero_id bigint, p_cliente_id bigint) returns public.clickup_destino
language sql stable security definer set search_path = '' as $$
  select d.*
    from public.clickup_destino d
   where (d.tablero_id is null or d.tablero_id = p_tablero_id)
     and (d.cliente_id is null or d.cliente_id = p_cliente_id)
   order by (d.tablero_id is not null) desc, (d.cliente_id is not null) desc
   limit 1
$$;

create function public.mapeo_estados_clickup(p_tablero_id bigint default null) returns jsonb
language sql stable security definer set search_path = '' as $$
  select (select mapeo_estados from public.clickup_config)
         || coalesce((select mapeo_estados from public.clickup_tablero where id = p_tablero_id), '{}'::jsonb)
$$;

create function public._lista_con_destino_clickup(p_lista_id text) returns boolean
language sql stable security definer set search_path = '' as $$
  select p_lista_id is not null and exists (select 1 from public.clickup_destino where lista_id = p_lista_id)
$$;

create function public._encolar_clickup(p_item_id bigint, p_accion text) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_previa public.clickup_cola;
begin
  select * into v_previa from public.clickup_cola
   where item_id = p_item_id and estado = 'Pendiente' and (reservada_hasta is null or reservada_hasta < now())
   order by id desc limit 1;
  if found then
    if p_accion = 'archive' and v_previa.accion = 'create' then
      delete from public.clickup_cola where id = v_previa.id;
    elsif p_accion = 'archive' then
      update public.clickup_cola set accion = 'archive' where id = v_previa.id;
    elsif p_accion = 'mover' and v_previa.accion = 'update' then
      update public.clickup_cola set accion = 'mover' where id = v_previa.id;
    end if;
    return;
  end if;
  if p_accion = 'archive' and (select clickup_task_id from public.item where id = p_item_id) is null then
    return;
  end if;
  insert into public.clickup_cola (item_id, accion) values (p_item_id, p_accion);
end
$$;

create function public._registrar_sin_destino_clickup(p_item_id bigint, p_accion text, p_tablero_id bigint, p_cliente_id bigint)
returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_error text := 'Sin destino configurado para '
    || coalesce((select nombre from public.clickup_tablero where id = p_tablero_id), '(sin tablero)') || ' / '
    || coalesce((select nombre from public.cliente where id = p_cliente_id), '(sin cliente)');
begin
  if exists (
    select 1 from public.clickup_cola where item_id = p_item_id and estado = 'Fallida' and error = v_error
  ) then
    return;
  end if;
  insert into public.clickup_cola (item_id, accion, estado, error, procesado_en)
  values (p_item_id, p_accion, 'Fallida', v_error, now());
end
$$;

create or replace function public.encolar_clickup() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_accion text;
  v_tablero bigint;
  v_destino public.clickup_destino;
begin
  if coalesce(current_setting('po.origen', true), '') = 'clickup' then
    return null;
  end if;
  if not coalesce((select habilitado from public.clickup_config), false) then
    return null;
  end if;

  if new.eliminado_en is not null then
    if tg_op = 'INSERT' or old.eliminado_en is not null then
      return null;
    end if;
    perform public._encolar_clickup(new.id, 'archive');
    return null;
  end if;

  v_accion := case when new.clickup_task_id is null then 'create' else 'update' end;
  select tablero_id into v_tablero from public.persona where id = new.responsable_id;
  select * into v_destino from public.destino_clickup(v_tablero, new.cliente_id);
  if v_accion = 'create' and v_destino.id is null then
    perform public._registrar_sin_destino_clickup(new.id, v_accion, v_tablero, new.cliente_id);
    return null;
  end if;
  if v_accion = 'update' and public._lista_con_destino_clickup(new.clickup_lista_id) then
    if v_destino.id is null then
      perform public._registrar_sin_destino_clickup(new.id, 'mover', v_tablero, new.cliente_id);
    elsif new.clickup_lista_id <> v_destino.lista_id then
      v_accion := 'mover';
    end if;
  end if;
  perform public._encolar_clickup(new.id, v_accion);
  return null;
end
$$;

create function public.encolar_mover_por_persona() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_item public.item;
  v_destino public.clickup_destino;
begin
  if coalesce(current_setting('po.origen', true), '') = 'clickup' then
    return null;
  end if;
  if not coalesce((select habilitado from public.clickup_config), false) then
    return null;
  end if;
  for v_item in
    select * from public.item
     where responsable_id = new.id
       and eliminado_en is null
       and clickup_task_id is not null
       and estado not in ('Terminado', 'Suspendido')
  loop
    if public._lista_con_destino_clickup(v_item.clickup_lista_id) then
      select * into v_destino from public.destino_clickup(new.tablero_id, v_item.cliente_id);
      if v_destino.id is null then
        perform public._registrar_sin_destino_clickup(v_item.id, 'mover', new.tablero_id, v_item.cliente_id);
      elsif v_item.clickup_lista_id <> v_destino.lista_id then
        perform public._encolar_clickup(v_item.id, 'mover');
      end if;
    end if;
  end loop;
  return null;
end
$$;

create trigger encolar_mover_persona
  after update of tablero_id on public.persona
  for each row
  when (old.tablero_id is distinct from new.tablero_id)
  execute function public.encolar_mover_por_persona();

create or replace function public.encolar_sin_vincular_clickup() returns integer
language plpgsql security definer set search_path = '' as $$
declare
  v_encolados integer;
begin
  with nuevos as (
    insert into public.clickup_cola (item_id, accion)
    select i.id, 'create'
      from public.item i
     where i.eliminado_en is null
       and i.clickup_task_id is null
       and (public.destino_clickup(
              (select p.tablero_id from public.persona p where p.id = i.responsable_id), i.cliente_id)).id is not null
       and not exists (
         select 1 from public.clickup_cola c where c.item_id = i.id and c.estado = 'Pendiente' and c.accion = 'create'
       )
    returning 1
  )
  select count(*) into v_encolados from nuevos;
  return v_encolados;
end
$$;

