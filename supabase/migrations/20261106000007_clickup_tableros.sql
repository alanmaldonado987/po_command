create table public.clickup_tablero (
  id bigint generated by default as identity primary key,
  nombre text not null check (btrim(nombre) <> ''),
  mapeo_estados jsonb
);
create unique index clickup_tablero_nombre_ux on public.clickup_tablero (lower(btrim(nombre)));

alter table public.clickup_tablero enable row level security;
create policy acceso_autenticado on public.clickup_tablero for all to authenticated using (true) with check (true);
create trigger auditar_clickup_tablero after insert or update or delete on public.clickup_tablero
  for each row execute function public.auditar();

alter table public.persona
  add column tablero_id bigint references public.clickup_tablero (id) on delete set null;

alter table public.clickup_destino
  add column tablero_id bigint references public.clickup_tablero (id) on delete cascade;
drop index public.clickup_destino_cliente_ux;
drop index public.clickup_destino_defecto_ux;
create unique index clickup_destino_tablero_cliente_ux
  on public.clickup_destino (coalesce(tablero_id, 0), coalesce(cliente_id, 0));

alter table public.clickup_cola drop constraint clickup_cola_accion_check;
alter table public.clickup_cola
  add constraint clickup_cola_accion_check check (accion in ('create', 'update', 'archive', 'mover'));

alter table public.item add column clickup_lista_id text;

