create view public.v_item with (security_invoker = true) as
with base as (
  select i.*,
         coalesce(i.plan_pruebas_fin, i.plan_fin) as fecha_compromiso,
         coalesce(i.real_pruebas_fin, i.real_fin) as fecha_entrega
  from public.item i
  where i.eliminado_en is null
),
calculado as (
  select b.*,
         case
           when b.fecha_compromiso is null then 0
           when b.estado = 'Terminado' then greatest(coalesce(b.fecha_entrega, b.fecha_compromiso) - b.fecha_compromiso, 0)
           when b.estado = 'Suspendido' then 0
           else greatest(public.hoy() - b.fecha_compromiso, 0)
         end as atraso_dias
  from base b
)
select c.*,
       case
         when lower(c.funcionalidad) = 'completo' then coalesce(m.nombre, '') || ' · completo'
         else c.funcionalidad
       end as titulo,
       c.estado not in ('Terminado', 'Suspendido') and c.atraso_dias > 0 as atrasado,
       pr.nombre as producto,
       cl.nombre as cliente,
       ac.nombre as actividad,
       m.nombre as modulo,
       pe.nombre as responsable,
       pe.correo as responsable_correo
from calculado c
left join public.producto pr on pr.id = c.producto_id
left join public.cliente cl on cl.id = c.cliente_id
left join public.actividad ac on ac.id = c.actividad_id
left join public.modulo m on m.id = c.modulo_id
left join public.persona pe on pe.id = c.responsable_id;

create view public.v_bloqueante_abierto with (security_invoker = true) as
select b.id, b.item_id, b.motivo, b.severidad, b.abierto_en, b.escalado_en,
       i.codigo, i.titulo, i.cliente_id, i.cliente, i.actividad, i.modulo, i.responsable, i.fecha_compromiso
from public.bloqueante b
join public.v_item i on i.id = b.item_id
where b.resuelto_en is null;

create or replace function public.tocar_actualizado() returns trigger
language plpgsql as $$
begin
  if (to_jsonb(new) - 'actualizado_en' - 'clickup_task_id' - 'clickup_url' - 'clickup_sync_en')
     = (to_jsonb(old) - 'actualizado_en' - 'clickup_task_id' - 'clickup_url' - 'clickup_sync_en') then
    return new;
  end if;
  new.actualizado_en := now();
  return new;
end
$$;

create or replace function public.auditar() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_fila jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  v_accion text := case tg_op when 'INSERT' then 'crear' when 'DELETE' then 'eliminar' else 'editar' end;
begin
  if tg_op = 'UPDATE'
     and (to_jsonb(new) - 'actualizado_en' - 'clickup_task_id' - 'clickup_url' - 'clickup_sync_en')
       = (to_jsonb(old) - 'actualizado_en' - 'clickup_task_id' - 'clickup_url' - 'clickup_sync_en') then
    return null;
  end if;
  if tg_op = 'UPDATE' and (to_jsonb(old) ->> 'eliminado_en') is null and (v_fila ->> 'eliminado_en') is not null then
    v_accion := 'eliminar';
  end if;
  insert into public.auditoria (entidad, entidad_id, accion, detalle)
  values (
    tg_table_name,
    (v_fila ->> 'id')::bigint,
    v_accion,
    concat_ws(' ', v_fila ->> 'codigo', v_fila ->> 'nombre', v_fila ->> 'funcionalidad', v_fila ->> 'titulo')
  );
  return null;
end
$$;

create function public.encolar_clickup() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_accion text;
  v_previa public.clickup_cola;
begin
  if coalesce(current_setting('po.origen', true), '') = 'clickup' then
    return null;
  end if;
  if not coalesce((select habilitado from public.clickup_config), false) then
    return null;
  end if;

  if new.eliminado_en is not null then
    if tg_op = 'INSERT' then
      return null;
    end if;
    if old.eliminado_en is not null then
      return null;
    end if;
    v_accion := 'archive';
  elsif new.clickup_task_id is null then
    v_accion := 'create';
  else
    v_accion := 'update';
  end if;

  select * into v_previa from public.clickup_cola
   where item_id = new.id and estado = 'Pendiente' and (reservada_hasta is null or reservada_hasta < now())
   order by id desc limit 1;
  if found then
    if v_accion = 'archive' and v_previa.accion = 'create' then
      delete from public.clickup_cola where id = v_previa.id;
    elsif v_accion = 'archive' then
      update public.clickup_cola set accion = 'archive' where id = v_previa.id;
    end if;
    return null;
  end if;

  if v_accion = 'archive' and new.clickup_task_id is null then
    return null;
  end if;
  insert into public.clickup_cola (item_id, accion) values (new.id, v_accion);
  return null;
end
$$;

create trigger encolar_clickup_alta after insert on public.item
  for each row execute function public.encolar_clickup();

create trigger encolar_clickup_cambio
